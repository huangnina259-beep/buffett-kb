@lru_cache(maxsize=16)
def _source(year, anchor, length):
    text = (ROOT/'data'/'clean_mds'/f'Buffett_{year}_Shareholder_Letter.md').read_text()
    start = text.index(anchor)
    excerpt = text[start:start+length]
    return {'source_file':f'Buffett_{year}_Shareholder_Letter.md','label':f'巴菲特{year}年股东信','title':f'巴菲特{year}年股东信','author':'Warren Buffett','year':year,'doc_type':'shareholder_letter','section':'','text':excerpt,'full_context':excerpt,'relevance':1.0}

def find_guide(question, history=None):
    if history:
        return None
    normalized = re.sub(r'[\s？?。！!，,：:]', '', question)
    for concept, guide in GUIDES.items():
        if normalized not in {concept, '什么是'+concept, concept+'是什么', concept+'是什么意思'}:
            continue
        try:
            sources = [dict(_source(*spec)) for spec in guide['sources']]
        except (OSError, ValueError):
            return None
        return {'answer':'*原典导读 · 预先核对的入门内容*\n\n'+guide['answer'], 'sources':sources, 'follow_ups':list(guide['follow_ups']), 'search_params':{'query':question,'answer_mode':'reviewed_guide'}, 'error':None}
    return None
